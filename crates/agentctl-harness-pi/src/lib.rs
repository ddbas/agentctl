//! `agentctl-harness-pi` — the pi coding agent harness integration.
//!
//! Writes (or deletes) a TypeScript extension at
//! `~/.pi/agent/extensions/agentctl.ts` that forwards pi's lifecycle events
//! to `agentctl agent event ...` / `agentctl agent clear`.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use agentctl_harness::{Harness, InstallSummary, UninstallSummary, tilde_collapse};

/// The TypeScript extension written to `~/.pi/agent/extensions/agentctl.ts`.
///
/// This content is embedded in the binary and versioned alongside `agentctl`.
/// Re-run `agentctl install pi` to update an existing file to this version.
const PI_EXTENSION_CONTENT: &str = r#"// Generated by agentctl install pi — do not edit by hand.
// Re-run `agentctl install pi` to update.
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { execFileSync } from "node:child_process";

function agentctl(...args: string[]): void {
  try {
    execFileSync("agentctl", args, { timeout: 5000, stdio: "ignore" });
  } catch {
    // Silently ignore errors (e.g. agentctl not in PATH, outside tmux)
  }
}

export default function (pi: ExtensionAPI) {
  let runId: string | undefined;

  pi.on("session_start", async () => {
    const sessionId = crypto.randomUUID();
    agentctl("agent", "event", "SESSION_STARTED", "--id", sessionId, "--harness", "pi");
  });

  pi.on("before_agent_start", async () => {
    runId = crypto.randomUUID();
    agentctl("agent", "event", "RUN_STARTED", "--id", runId, "--harness", "pi");
  });

  pi.on("agent_settled", async () => {
    if (runId) {
      agentctl("agent", "event", "RUN_FINISHED", "--id", runId, "--harness", "pi");
    }
  });

  pi.on("tool_call", async (event) => {
    agentctl("agent", "event", "TOOL_CALL_START", "--id", event.toolCallId, "--harness", "pi");
  });

  pi.on("tool_result", async (event) => {
    agentctl("agent", "event", "TOOL_CALL_RESULT", "--id", event.toolCallId, "--harness", "pi");
  });

  pi.on("session_shutdown", async () => {
    agentctl("agent", "clear");
  });
}
"#;

/// `Harness` implementation for the pi coding agent.
pub struct PiHarness;

impl Harness for PiHarness {
    fn name(&self) -> &'static str {
        "pi"
    }

    fn install(&self) -> Result<InstallSummary> {
        let path = default_pi_extension_path()?;
        install_pi_to(&path)
    }

    fn uninstall(&self) -> Result<UninstallSummary> {
        let path = default_pi_extension_path()?;
        uninstall_pi_to(&path)
    }
}

/// Resolve the default pi extensions directory: `~/.pi/agent/extensions/`.
///
/// Exposed as a separate function so unit tests can call `install_pi_to` with
/// a custom path, while production code uses this default.
fn default_pi_extension_path() -> Result<PathBuf> {
    let home = dirs::home_dir().context("could not determine home directory")?;
    Ok(home
        .join(".pi")
        .join("agent")
        .join("extensions")
        .join("agentctl.ts"))
}

#[derive(Debug, PartialEq)]
enum FileStatus {
    New,
    Unchanged,
    Updated,
}

/// Install the agentctl pi extension to the given path.
///
/// This is the testable core; [`PiHarness::install`] supplies the default
/// path.
pub fn install_pi_to(dest: &PathBuf) -> Result<InstallSummary> {
    // 1. Create parent directory if it does not exist.
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create directory {}", parent.display()))?;
    }

    // 2. Determine status: new, same, or updated.
    let status = if dest.exists() {
        let existing = fs::read_to_string(dest)
            .with_context(|| format!("failed to read {}", dest.display()))?;
        if existing == PI_EXTENSION_CONTENT {
            FileStatus::Unchanged
        } else {
            FileStatus::Updated
        }
    } else {
        FileStatus::New
    };

    // 3. Write if needed.
    if status != FileStatus::Unchanged {
        fs::write(dest, PI_EXTENSION_CONTENT)
            .with_context(|| format!("failed to write {}", dest.display()))?;
    }

    // 4. Build summary.
    Ok(InstallSummary(pi_install_summary(dest, status)))
}

fn pi_install_summary(dest: &Path, status: FileStatus) -> String {
    let path_display = tilde_collapse(dest);
    let mut lines = vec!["Installed agentctl extension for pi:".to_string()];

    match status {
        FileStatus::New | FileStatus::Updated => {
            let prefix = if status == FileStatus::New { "+" } else { "~" };
            lines.push(format!("  {prefix} {path_display}"));
            lines.push(
                "    session_start        → agentctl agent event SESSION_STARTED --harness pi"
                    .to_string(),
            );
            lines.push(
                "    before_agent_start   → agentctl agent event RUN_STARTED --harness pi"
                    .to_string(),
            );
            lines.push(
                "    agent_settled        → agentctl agent event RUN_FINISHED --harness pi"
                    .to_string(),
            );
            lines.push(
                "    tool_call            → agentctl agent event TOOL_CALL_START --harness pi"
                    .to_string(),
            );
            lines.push(
                "    tool_result          → agentctl agent event TOOL_CALL_RESULT --harness pi"
                    .to_string(),
            );
            lines.push("    session_shutdown     → agentctl agent clear".to_string());
        }
        FileStatus::Unchanged => {
            lines.push(format!("  = {path_display} (already up to date)"));
        }
    }

    lines.join("\n")
}

/// Uninstall the agentctl pi extension at the given path.
///
/// Deletes `dest` if it exists, regardless of its content (the file is
/// documented as agentctl-managed regardless of drift). No-op if `dest` does
/// not exist. Never removes the parent `extensions/` directory.
///
/// This is the testable core; [`PiHarness::uninstall`] supplies the default
/// path.
pub fn uninstall_pi_to(dest: &Path) -> Result<UninstallSummary> {
    let removed = dest.exists();
    if removed {
        fs::remove_file(dest).with_context(|| format!("failed to remove {}", dest.display()))?;
    }

    Ok(UninstallSummary(pi_uninstall_summary(dest, removed)))
}

fn pi_uninstall_summary(dest: &Path, removed: bool) -> String {
    let path_display = tilde_collapse(dest);
    let mut lines = vec!["Uninstalled agentctl extension for pi:".to_string()];
    if removed {
        lines.push(format!("  - {path_display}"));
    } else {
        lines.push(format!("  = {path_display} (nothing to remove)"));
    }
    lines.join("\n")
}

