//! `dv hooks` — hook registration for agent harnesses.
//!
//! Supported harnesses:
//! - `pi`: writes a TypeScript extension to `~/.pi/agent/extensions/drovr.ts`

use crate::Harness;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

// ── Embedded pi extension content ─────────────────────────────────────────────

/// The TypeScript extension written to `~/.pi/agent/extensions/drovr.ts`.
///
/// This content is embedded in the binary and versioned alongside `dv`.
/// Re-run `dv hooks install pi` to update an existing file to this version.
const PI_EXTENSION_CONTENT: &str = r#"// Generated by dv hooks install pi — do not edit by hand.
// Re-run `dv hooks install pi` to update.
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { execFileSync } from "node:child_process";

function dv(...args: string[]): void {
  try {
    execFileSync("dv", args, { timeout: 5000, stdio: "ignore" });
  } catch {
    // Silently ignore errors (e.g. dv not in PATH, outside tmux)
  }
}

export default function (pi: ExtensionAPI) {
  pi.on("session_start", async () => {
    dv("set-state", "idle", "--harness", "pi");
  });

  pi.on("before_agent_start", async () => {
    dv("set-state", "working", "--harness", "pi");
  });

  pi.on("agent_settled", async () => {
    dv("set-state", "done", "--harness", "pi");
  });

  pi.on("session_shutdown", async () => {
    dv("clear-state");
  });
}
"#;

// ── Public API ────────────────────────────────────────────────────────────────

/// Entry point for `dv hooks install <harness>`.
pub fn run_install(harness: Harness) -> Result<()> {
    match harness {
        Harness::Pi => install_pi(),
    }
}

// ── Pi harness ────────────────────────────────────────────────────────────────

/// Resolve the default pi extensions directory: `~/.pi/agent/extensions/`.
///
/// Exposed as a separate function so unit tests can call `install_pi_to` with
/// a custom path, while production code uses this default.
fn default_pi_extension_path() -> Result<PathBuf> {
    let home = dirs::home_dir().context("could not determine home directory")?;
    Ok(home
        .join(".pi")
        .join("agent")
        .join("extensions")
        .join("drovr.ts"))
}

/// Install the drovr pi extension to `~/.pi/agent/extensions/drovr.ts`.
fn install_pi() -> Result<()> {
    let path = default_pi_extension_path()?;
    install_pi_to(&path)
}

/// Install the drovr pi extension to the given path.
///
/// This is the testable core; production code calls `install_pi()` which
/// supplies the default path.
pub fn install_pi_to(dest: &PathBuf) -> Result<()> {
    // 1. Create parent directory if it does not exist.
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create directory {}", parent.display()))?;
    }

    // 2. Determine status: new, same, or updated.
    let status = if dest.exists() {
        let existing = fs::read_to_string(dest)
            .with_context(|| format!("failed to read {}", dest.display()))?;
        if existing == PI_EXTENSION_CONTENT {
            FileStatus::Unchanged
        } else {
            FileStatus::Updated
        }
    } else {
        FileStatus::New
    };

    // 3. Write if needed.
    if status != FileStatus::Unchanged {
        fs::write(dest, PI_EXTENSION_CONTENT)
            .with_context(|| format!("failed to write {}", dest.display()))?;
    }

    // 4. Print summary.
    print_pi_summary(dest, status);

    Ok(())
}

#[derive(Debug, PartialEq)]
enum FileStatus {
    New,
    Unchanged,
    Updated,
}

fn print_pi_summary(dest: &Path, status: FileStatus) {
    let path_display = tilde_collapse(dest);

    println!("Installed drovr extension for pi:");

    match status {
        FileStatus::New | FileStatus::Updated => {
            let prefix = if status == FileStatus::New { "+" } else { "~" };
            println!("  {prefix} {path_display}");
            println!("    session_start        → dv set-state idle --harness pi");
            println!("    before_agent_start   → dv set-state working --harness pi");
            println!("    agent_settled        → dv set-state done --harness pi");
            println!("    session_shutdown     → dv clear-state");
        }
        FileStatus::Unchanged => {
            println!("  = {path_display} (already up to date)");
        }
    }
}

/// Replace the home directory prefix with `~` for human-readable output.
fn tilde_collapse(path: &Path) -> String {
    if let Some(home) = dirs::home_dir()
        && let Ok(rel) = path.strip_prefix(&home)
    {
        return format!("~/{}", rel.display());
    }
    path.display().to_string()
}

// ── Unit tests ────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    fn ext_path(dir: &TempDir) -> PathBuf {
        dir.path()
            .join(".pi")
            .join("agent")
            .join("extensions")
            .join("drovr.ts")
    }

    // ── task 2.1: new install creates file with all four event handlers ───────

    #[test]
    fn install_pi_creates_file_when_absent() {
        let tmp = TempDir::new().unwrap();
        let dest = ext_path(&tmp);

        // File and parent directory do not exist yet.
        assert!(!dest.exists());

        install_pi_to(&dest).expect("install_pi_to should succeed");

        let content = fs::read_to_string(&dest).expect("file should exist");
        assert_eq!(
            content, PI_EXTENSION_CONTENT,
            "written content should match embedded constant"
        );
    }

    // ── task 2.2: idempotent re-run ───────────────────────────────────────────

    #[test]
    fn install_pi_idempotent_no_write_on_second_run() {
        let tmp = TempDir::new().unwrap();
        let dest = ext_path(&tmp);

        install_pi_to(&dest).expect("first install");

        // Record modification time before second run.
        let mtime_before = fs::metadata(&dest).unwrap().modified().unwrap();

        // Small sleep to ensure mtime would change if a write occurred.
        std::thread::sleep(std::time::Duration::from_millis(10));

        install_pi_to(&dest).expect("second install");

        let mtime_after = fs::metadata(&dest).unwrap().modified().unwrap();
        assert_eq!(
            mtime_before, mtime_after,
            "file should not be rewritten on idempotent re-run"
        );
    }

    // ── task 2.3: overwrites stale file ──────────────────────────────────────

    #[test]
    fn install_pi_overwrites_stale_file() {
        let tmp = TempDir::new().unwrap();
        let dest = ext_path(&tmp);

        // Create parent dirs and write stale content.
        fs::create_dir_all(dest.parent().unwrap()).unwrap();
        fs::write(&dest, "// old version").unwrap();

        install_pi_to(&dest).expect("install over stale file");

        let content = fs::read_to_string(&dest).unwrap();
        assert_eq!(
            content, PI_EXTENSION_CONTENT,
            "stale file should be overwritten"
        );
    }

    // ── task 2.4: creates directory when missing ──────────────────────────────

    #[test]
    fn install_pi_creates_extensions_directory() {
        let tmp = TempDir::new().unwrap();
        let dest = ext_path(&tmp);

        // Parent directory does NOT exist.
        assert!(!dest.parent().unwrap().exists());

        install_pi_to(&dest).expect("should create dir and file");

        assert!(
            dest.parent().unwrap().exists(),
            "extensions directory should be created"
        );
        assert!(dest.exists(), "drovr.ts should be created");
    }

    // ── task 2.5: generated content has all four event handlers ──────────────

    #[test]
    fn extension_content_has_all_four_handlers() {
        assert!(
            PI_EXTENSION_CONTENT.contains(r#"pi.on("session_start""#),
            "should handle session_start"
        );
        assert!(
            PI_EXTENSION_CONTENT.contains(r#"dv("set-state", "idle", "--harness", "pi")"#),
            "session_start should call dv set-state idle"
        );

        assert!(
            PI_EXTENSION_CONTENT.contains(r#"pi.on("before_agent_start""#),
            "should handle before_agent_start"
        );
        assert!(
            PI_EXTENSION_CONTENT.contains(r#"dv("set-state", "working", "--harness", "pi")"#),
            "before_agent_start should call dv set-state working"
        );

        assert!(
            PI_EXTENSION_CONTENT.contains(r#"pi.on("agent_settled""#),
            "should handle agent_settled"
        );
        assert!(
            PI_EXTENSION_CONTENT.contains(r#"dv("set-state", "done", "--harness", "pi")"#),
            "agent_settled should call dv set-state done"
        );

        assert!(
            PI_EXTENSION_CONTENT.contains(r#"pi.on("session_shutdown""#),
            "should handle session_shutdown"
        );
        assert!(
            PI_EXTENSION_CONTENT.contains(r#"dv("clear-state")"#),
            "session_shutdown should call dv clear-state"
        );
    }

    // ── run_install dispatches to pi ──────────────────────────────────────────

    #[test]
    fn run_install_pi_creates_file() {
        let tmp = TempDir::new().unwrap();
        let dest = ext_path(&tmp);
        // Use install_pi_to directly; run_install wires to the real home dir.
        install_pi_to(&dest).expect("install should succeed");
        assert!(dest.exists());
    }
}
