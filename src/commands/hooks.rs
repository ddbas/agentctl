//! `rd install` / `rd uninstall` — install or remove radr on agent harnesses.
//!
//! Today this means installing (or removing) hook integrations, but may
//! include more in the future. Supported harnesses:
//! - `pi`: writes (or deletes) a TypeScript extension at
//!   `~/.pi/agent/extensions/radr.ts`.
//! - `claude`: writes (or removes) a self-contained Claude Code plugin at
//!   `~/.claude/skills/radr/`, containing `.claude-plugin/plugin.json` and
//!   `hooks/hooks.json`. Install is remove-then-write (no merge/diff against
//!   an existing installation); this command never reads or writes
//!   `~/.claude/settings.json`.
//!
//! `rd uninstall <harness>` is the structural inverse of `rd install
//! <harness>` and shares the same `Harness` enum, so both dispatches
//! (`run_install`, `run_uninstall`) must remain exhaustive matches with no
//! wildcard arm.

use crate::Harness;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde_json::json;

// ── Embedded pi extension content ─────────────────────────────────────────────

/// The TypeScript extension written to `~/.pi/agent/extensions/radr.ts`.
///
/// This content is embedded in the binary and versioned alongside `rd`.
/// Re-run `rd install pi` to update an existing file to this version.
const PI_EXTENSION_CONTENT: &str = r#"// Generated by rd install pi — do not edit by hand.
// Re-run `rd install pi` to update.
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { execFileSync } from "node:child_process";

function rd(...args: string[]): void {
  try {
    execFileSync("rd", args, { timeout: 5000, stdio: "ignore" });
  } catch {
    // Silently ignore errors (e.g. rd not in PATH, outside tmux)
  }
}

export default function (pi: ExtensionAPI) {
  let runId: string | undefined;

  pi.on("session_start", async () => {
    const sessionId = crypto.randomUUID();
    rd("agent", "event", "SESSION_STARTED", "--id", sessionId, "--harness", "pi");
  });

  pi.on("before_agent_start", async () => {
    runId = crypto.randomUUID();
    rd("agent", "event", "RUN_STARTED", "--id", runId, "--harness", "pi");
  });

  pi.on("agent_settled", async () => {
    if (runId) {
      rd("agent", "event", "RUN_FINISHED", "--id", runId, "--harness", "pi");
    }
  });

  pi.on("tool_call", async (event) => {
    rd("agent", "event", "TOOL_CALL_START", "--id", event.toolCallId, "--harness", "pi");
  });

  pi.on("tool_result", async (event) => {
    rd("agent", "event", "TOOL_CALL_RESULT", "--id", event.toolCallId, "--harness", "pi");
  });

  pi.on("session_shutdown", async () => {
    rd("agent", "clear");
  });
}
"#;

// ── Public API ────────────────────────────────────────────────────────────────

/// Entry point for `rd install <harness>`.
pub fn run_install(harness: Harness) -> Result<()> {
    match harness {
        Harness::Pi => install_pi(),
        Harness::Claude => install_claude(),
    }
}

/// Entry point for `rd uninstall <harness>`.
pub fn run_uninstall(harness: Harness) -> Result<()> {
    match harness {
        Harness::Pi => uninstall_pi(),
        Harness::Claude => uninstall_claude(),
    }
}

// ── Pi harness ────────────────────────────────────────────────────────────────

/// Resolve the default pi extensions directory: `~/.pi/agent/extensions/`.
///
/// Exposed as a separate function so unit tests can call `install_pi_to` with
/// a custom path, while production code uses this default.
fn default_pi_extension_path() -> Result<PathBuf> {
    let home = dirs::home_dir().context("could not determine home directory")?;
    Ok(home
        .join(".pi")
        .join("agent")
        .join("extensions")
        .join("radr.ts"))
}

/// Install the radr pi extension to `~/.pi/agent/extensions/radr.ts`.
fn install_pi() -> Result<()> {
    let path = default_pi_extension_path()?;
    install_pi_to(&path)
}

/// Install the radr pi extension to the given path.
///
/// This is the testable core; production code calls `install_pi()` which
/// supplies the default path.
pub fn install_pi_to(dest: &PathBuf) -> Result<()> {
    // 1. Create parent directory if it does not exist.
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create directory {}", parent.display()))?;
    }

    // 2. Determine status: new, same, or updated.
    let status = if dest.exists() {
        let existing = fs::read_to_string(dest)
            .with_context(|| format!("failed to read {}", dest.display()))?;
        if existing == PI_EXTENSION_CONTENT {
            FileStatus::Unchanged
        } else {
            FileStatus::Updated
        }
    } else {
        FileStatus::New
    };

    // 3. Write if needed.
    if status != FileStatus::Unchanged {
        fs::write(dest, PI_EXTENSION_CONTENT)
            .with_context(|| format!("failed to write {}", dest.display()))?;
    }

    // 4. Print summary.
    print_pi_summary(dest, status);

    Ok(())
}

#[derive(Debug, PartialEq)]
enum FileStatus {
    New,
    Unchanged,
    Updated,
}

/// Uninstall the radr pi extension from `~/.pi/agent/extensions/radr.ts`.
fn uninstall_pi() -> Result<()> {
    let path = default_pi_extension_path()?;
    uninstall_pi_to(&path)
}

/// Uninstall the radr pi extension at the given path.
///
/// Deletes `dest` if it exists, regardless of its content (the file is
/// documented as radr-managed regardless of drift). No-op if `dest` does not
/// exist. Never removes the parent `extensions/` directory.
///
/// This is the testable core; production code calls `uninstall_pi()` which
/// supplies the default path.
pub fn uninstall_pi_to(dest: &Path) -> Result<()> {
    let removed = dest.exists();
    if removed {
        fs::remove_file(dest).with_context(|| format!("failed to remove {}", dest.display()))?;
    }

    print_pi_uninstall_summary(dest, removed);

    Ok(())
}

fn print_pi_uninstall_summary(dest: &Path, removed: bool) {
    let path_display = tilde_collapse(dest);

    println!("Uninstalled radr extension for pi:");
    if removed {
        println!("  - {path_display}");
    } else {
        println!("  = {path_display} (nothing to remove)");
    }
}

fn print_pi_summary(dest: &Path, status: FileStatus) {
    let path_display = tilde_collapse(dest);

    println!("Installed radr extension for pi:");

    match status {
        FileStatus::New | FileStatus::Updated => {
            let prefix = if status == FileStatus::New { "+" } else { "~" };
            println!("  {prefix} {path_display}");
            println!("    session_start        → rd agent event SESSION_STARTED --harness pi");
            println!("    before_agent_start   → rd agent event RUN_STARTED --harness pi");
            println!("    agent_settled        → rd agent event RUN_FINISHED --harness pi");
            println!("    tool_call            → rd agent event TOOL_CALL_START --harness pi");
            println!("    tool_result          → rd agent event TOOL_CALL_RESULT --harness pi");
            println!("    session_shutdown     → rd agent clear");
        }
        FileStatus::Unchanged => {
            println!("  = {path_display} (already up to date)");
        }
    }
}

/// Replace the home directory prefix with `~` for human-readable output.
pub(crate) fn tilde_collapse(path: &Path) -> String {
    if let Some(home) = dirs::home_dir()
        && let Ok(rel) = path.strip_prefix(&home)
    {
        return format!("~/{}", rel.display());
    }
    path.display().to_string()
}

